    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        enableEdgeToEdge()
        setContent {
            MobileTunerTheme {
                Scaffold(modifier = Modifier.fillMaxSize()) { innerPadding ->
                    DebugScreen(modifier = Modifier.padding(innerPadding))
                }
            }
        }
    }
}

/**
 * Temporary screen proving mic -> DSP thread -> core -> UI. Replaced by the real UI later.
 * Generated by AI
 * */
@Composable
fun DebugScreen(modifier: Modifier = Modifier, vm: TunerViewModel = viewModel()) {
    val context = LocalContext.current
    var granted by remember {
        mutableStateOf(
            ContextCompat.checkSelfPermission(context, Manifest.permission.RECORD_AUDIO) ==
                PackageManager.PERMISSION_GRANTED
        )
    }
    val launcher = rememberLauncherForActivityResult(ActivityResultContracts.RequestPermission()) {
        granted = it
    }
    LaunchedEffect(Unit) {
        if (!granted) launcher.launch(Manifest.permission.RECORD_AUDIO)
    }

    if (granted) {
        RunWhileStarted(vm.engine)
    }

    // The UI never waits on DSP: it samples the latest snapshot about 30 times per second.
    var snap by remember { mutableStateOf(vm.engine.latest) }
    var learning by remember { mutableStateOf(false) }
    var noiseError by remember { mutableStateOf<String?>(null) }
    LaunchedEffect(Unit) {
        while (true) {
            snap = vm.engine.latest
            learning = vm.engine.isLearningNoise
            noiseError = vm.engine.noiseError
            delay(33)
        }
    }

    Column(modifier = modifier.padding(16.dp)) {
        if (!granted) Text("Microphone permission denied")
        Text("hops: ${snap.hops}")
        Text("dropped: ${snap.dropped}")
        Text("rms: ${snap.result?.rms ?: "-"}")
        Text("pitch: ${snap.result?.pitchHz ?: "-"} Hz")
        snap.coreError?.let { Text("core: $it") }
        Button(onClick = { vm.engine.requestNoiseLearning() }, enabled = granted && !learning) {
            Text(if (learning) "Learning noise… stay quiet" else "Calibrate")
        }
        noiseError?.let { Text("calibration failed: $it") }
    }
}

/** Capture runs only while the activity is visible (SPEC: nothing runs in the background). */
@SuppressLint("MissingPermission") // only composed once RECORD_AUDIO is granted
@Composable
private fun RunWhileStarted(engine: TunerEngine) {
    LifecycleStartEffect(engine) {
        engine.start()
        onStopOrDispose {
            engine.stop()
        }
    }
}
