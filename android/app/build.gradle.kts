// Builds dsp-core (.so into jniLibs) and generates the Kotlin bindings before every build.
// Up to date, and skipped, while nothing in dsp-core changes.
val repoRoot = rootDir.parentFile
val buildRust by tasks.registering(Exec::class) {
    workingDir = repoRoot
    commandLine("bash", "scripts/build-android.sh")
    // Android Studio started from the Dock does not see the shell profile, so cargo is not on PATH.
    environment("PATH", "${System.getProperty("user.home")}/.cargo/bin:${System.getenv("PATH")}")

    inputs.file(repoRoot.resolve("scripts/build-android.sh"))
    inputs.dir(repoRoot.resolve("dsp-core/src"))
    inputs.files(
        repoRoot.resolve("dsp-core/Cargo.toml"),
        repoRoot.resolve("dsp-core/Cargo.lock"),
        repoRoot.resolve("dsp-core/uniffi.toml"),
    )
    outputs.dir(layout.projectDirectory.dir("src/main/jniLibs"))
    outputs.dir(layout.buildDirectory.dir("generated/uniffi"))
}
tasks.named("preBuild") { dependsOn(buildRust) }
